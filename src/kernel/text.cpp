static int sorted_idx[512];
static bool sorted_ready = false;

static void build_sorted() {
    sorted_ready = true;
    int n = min(N_EMOJI, 512);
    for (int i = 0; i < n; i++) sorted_idx[i] = i;
    for (int i = 1; i < n; i++) {                            // insertion sort by code point
        int v = sorted_idx[i], j = i - 1;
        while (j >= 0 && emoji_table[sorted_idx[j]].cp > emoji_table[v].cp) { sorted_idx[j + 1] = sorted_idx[j]; j--; }
        sorted_idx[j + 1] = v;
    }
}

int emoji_count() { return N_EMOJI; }
u32 emoji_codepoint(int idx) { return idx >= 1 && idx <= N_EMOJI ? emoji_table[idx - 1].cp : 0; }
const char* emoji_name(int idx) { return idx >= 1 && idx <= N_EMOJI ? emoji_table[idx - 1].name : ""; }

static int direct_index(u32 cp) {
    if (!sorted_ready) build_sorted();
    int lo = 0, hi = min(N_EMOJI, 512) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        u32 c = emoji_table[sorted_idx[mid]].cp;
        if (c == cp) return sorted_idx[mid] + 1;
        if (c < cp) lo = mid + 1; else hi = mid - 1;
    }
    return 0;
}

int emoji_index(u32 cp) {
    if (cp < 0x203C) return 0;
    int i = direct_index(cp);
    if (i) return i;
    for (auto& a : emoji_alias) if (a.cp == cp) return a.as ? direct_index(a.as) : -1;     // -1: a modifier to drop
    return 0;
}

int emoji_find(const char* part, int start) {
    for (int i = max(start, 1); i <= N_EMOJI; i++) if (!part[0] || str_icontains(emoji_table[i - 1].name, part)) return i;
    return 0;
}

// sprites: set up by the asset loader once the sheet is decoded
static Image sprites16[512], sprites12[512];
static int sprites_n = 0;

void emoji_install_sheet(const Image& sheet) {
    int cols = sheet.w / 16;
    sprites_n = min(N_EMOJI, 512);
    for (int i = 0; i < sprites_n; i++) {
        Image s = image_new(16, 16, 0);
        int sx = (i % cols) * 16, sy = (i / cols) * 16;
        for (int y = 0; y < 16; y++) memcpy(s.px + y * 16, sheet.px + (sy + y) * sheet.w + sx, 64);
        sprites16[i] = s;
        Image t = image_new(16, 16, 0);
        memcpy(t.px, s.px, 16 * 16 * 4);
        image_shrink(t, 12, 12);
        sprites12[i] = t;
    }
}

const Image* emoji_sprite(int idx, int px) {
    if (idx < 1 || idx > sprites_n) return nullptr;
    return px == 12 ? &sprites12[idx - 1] : &sprites16[idx - 1];
}

// ---------------------------------------------------------------- UTF-8
u32 utf8_decode(const char*& p, const char* end) {
    u8 c = (u8)*p++;
    if (c < 0x80) return c;
    int extra;
    u32 cp;
    if ((c & 0xE0) == 0xC0) { cp = c & 0x1F; extra = 1; }
    else if ((c & 0xF0) == 0xE0) { cp = c & 0x0F; extra = 2; }
    else if ((c & 0xF8) == 0xF0) { cp = c & 0x07; extra = 3; }
    else return c;
    for (int k = 0; k < extra; k++) {
        if (p >= end || ((u8)*p & 0xC0) != 0x80) return 0xFFFD;
        cp = (cp << 6) | ((u8)*p++ & 0x3F);
    }
    return cp;
}

int utf8_len_at(const char* p, const char* end) {
    u8 c = (u8)*p;
    int n = c < 0x80 ? 1 : (c & 0xE0) == 0xC0 ? 2 : (c & 0xF0) == 0xE0 ? 3 : (c & 0xF8) == 0xF0 ? 4 : 1;
    if (p + n > end) n = (int)(end - p);
    for (int k = 1; k < n; k++) if (((u8)p[k] & 0xC0) != 0x80) return k;
    return max(n, 1);
}

int utf8_encode(u32 cp, char* out) {
    if (cp < 0x80) { out[0] = (char)cp; return 1; }
    if (cp < 0x800) { out[0] = (char)(0xC0 | (cp >> 6)); out[1] = (char)(0x80 | (cp & 0x3F)); return 2; }
    if (cp < 0x10000) { out[0] = (char)(0xE0 | (cp >> 12)); out[1] = (char)(0x80 | ((cp >> 6) & 0x3F)); out[2] = (char)(0x80 | (cp & 0x3F)); return 3; }
    out[0] = (char)(0xF0 | (cp >> 18)); out[1] = (char)(0x80 | ((cp >> 12) & 0x3F));
    out[2] = (char)(0x80 | ((cp >> 6) & 0x3F)); out[3] = (char)(0x80 | (cp & 0x3F));
    return 4;
}

// ---------------------------------------------------------------- code point -> silicon codepage
int glyph_for(u32 cp, char* out) {
    if (cp < 0x80) { if (cp == '\r') return 0; out[0] = (char)cp; return 1; }
    int e = emoji_index(cp);
    if (e < 0) return 0;
    if (e > 0) { emoji_to_bytes(e, out); return 2; }
    if (cp >= 0xA0 && cp <= 0xFF) {
        static const char* lat = "AAAAAAACEEEEIIIIDNOOOOOxOUUUUYTsaaaaaaaceeeeiiiidnooooo/ouuuuyty";
        if (cp >= 0xC0) { out[0] = lat[cp - 0xC0]; return 1; }
        switch (cp) {
        case 0xA0: out[0] = ' '; return 1;
        case 0xA9: memcpy(out, "(c)", 3); return 3;
        case 0xAE: memcpy(out, "(r)", 3); return 3;
        case 0xB0: out[0] = '\x96'; return 1;
        case 0xB7: out[0] = '\x93'; return 1;
        case 0xAD: return 0;
        default: out[0] = '?'; return 1;
        }
    }
    if (cp >= 0x100 && cp <= 0x17F) {
        static const char* ext = "AaAaAaCcCcCcCcDdDdEeEeEeEeEeGgGgGgGgHhHhIiIiIiIiIiJjJjKkkLlLlLlLlLlNnNnNnnNnOoOoOoOoRrRrRrSsSsSsSsTtTtTtUuUuUuUuUuUuWwYyYZzZzZzs";
        out[0] = ext[cp - 0x100];
        return 1;
    }
    switch (cp) {
    case 0x2018: case 0x2019: case 0x201A: case 0x2032: out[0] = '\''; return 1;
    case 0x201C: case 0x201D: case 0x201E: case 0x2033: out[0] = '"'; return 1;
    case 0x2010: case 0x2011: case 0x2012: case 0x2013: case 0x2014: case 0x2015: case 0x2212: out[0] = '-'; return 1;
    case 0x2026: memcpy(out, "...", 3); return 3;
    case 0x2022: case 0x25CF: case 0x25AA: case 0x2023: out[0] = '\x93'; return 1;
    case 0x2190: out[0] = '\x8f'; return 1;
    case 0x2192: out[0] = '\x90'; return 1;
    case 0x2191: out[0] = '\x91'; return 1;
    case 0x2193: out[0] = '\x92'; return 1;
    case 0x2713: out[0] = '\x94'; return 1;
    case 0x2665: out[0] = '\x9d'; return 1;
    case 0x25B6: case 0x25BA: out[0] = '\x98'; return 1;
    case 0x25C0: case 0x25C4: out[0] = '\x99'; return 1;
    case 0x25B2: out[0] = '\x9a'; return 1;
    case 0x25BC: out[0] = '\x9b'; return 1;
    case 0x2588: out[0] = '\x80'; return 1;
    case 0x2593: out[0] = '\x81'; return 1;
    case 0x2592: out[0] = '\x82'; return 1;
    case 0x2591: out[0] = '\x83'; return 1;
    case 0x2500: out[0] = '\x84'; return 1;
    case 0x2502: out[0] = '\x85'; return 1;
    case 0xD7: out[0] = 'x'; return 1;
    case 0x2122: memcpy(out, "(tm)", 4); return 4;
    case 0x200B: case 0xFEFF: case 0x200D: case 0x200E: case 0x200F: return 0;
    }
    if (cp >= 0xFE00 && cp <= 0xFE0F) return 0;
    if (cp >= 0x1F3FB && cp <= 0x1F3FF) return 0;
    out[0] = '?';
    return 1;
}

void utf8_to_silicon(const char* in, u32 len, char* out, u32 cap) {
    const char* p = in;
    const char* end = in + len;
    u32 o = 0;
    while (p < end && o + 6 < cap) {
        u32 cp = utf8_decode(p, end);
        o += glyph_for(cp, out + o);
    }
    out[o] = 0;
}

void silicon_to_utf8(const char* in, u32 len, char* out, u32 cap) {
    u32 o = 0;
    for (u32 i = 0; i < len && o + 5 < cap; i++) {
        u8 c = (u8)in[i];
        if (is_emoji_lead(c) && i + 1 < len && in[i + 1]) {
            u32 cp = emoji_codepoint(emoji_from_bytes(c, (u8)in[i + 1]));
            i++;
            if (cp) { o += utf8_encode(cp, out + o); continue; }
            out[o++] = '?';
            continue;
        }
        u32 cp = c;
        if (c >= 0x80) {
            switch (c) {
            case 0x8f: cp = 0x2190; break;
            case 0x90: cp = 0x2192; break;
            case 0x91: cp = 0x2191; break;
            case 0x92: cp = 0x2193; break;
            case 0x93: cp = 0x2022; break;
            case 0x94: cp = 0x2713; break;
            case 0x96: cp = 0xB0; break;
            case 0x97: cp = 0x2026; break;
            case 0x9d: cp = 0x2665; break;
            default: if (c < 0xA0) cp = '?'; break;
            }
        }
        o += utf8_encode(cp, out + o);
    }
    out[o] = 0;
}
