"""Build the silicon 8x12 pixel font from tools/font.txt.

Writes src/kernel/gfx/font_data.inc (u8 rows[256][12], bit 7 = leftmost pixel)
and optionally a preview PNG.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H = 8, 12


def parse(path):
    glyphs = {}
    cur = None
    rows = []
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("#") and not line.startswith("#.") and not line.startswith("##") and cur is None:
            continue
        if line.startswith("== "):
            if cur is not None:
                glyphs[cur] = rows
            name = line[3:]
            if name == "space":
                cur = 32
            elif len(name) == 1:
                cur = ord(name)
            else:
                cur = int(name)
            rows = []
        elif cur is not None and line:
            rows.append(line)
    if cur is not None:
        glyphs[cur] = rows
    return glyphs


def to_bits(rows):
    out = [0] * H
    for i, r in enumerate(rows[:10]):
        v = 0
        for x, ch in enumerate(r[:8]):
            if ch == "#":
                v |= 0x80 >> x
        out[i + 1] = v
    return out


def generated():
    g = {}
    full = [0xFF] * H
    g[128] = full
    g[129] = [0xEE if y % 2 == 0 else 0xBB for y in range(H)]   # dark shade
    g[130] = [0xAA if y % 2 == 0 else 0x55 for y in range(H)]   # medium shade
    g[131] = [0x88 if y % 2 == 0 else 0x22 for y in range(H)]   # light shade
    mid_r = 5
    mid_c = 0x10  # column 3
    left = 0xF0   # cols 0..3
    right = 0x1F  # cols 3..7

    def box(up, down, l, r):
        rows = [0] * H
        for y in range(H):
            if (up and y <= mid_r) or (down and y >= mid_r):
                rows[y] |= mid_c
        if l:
            rows[mid_r] |= left
        if r:
            rows[mid_r] |= right
        return rows

    g[132] = box(0, 0, 1, 1)  # ─
    g[133] = box(1, 1, 0, 0)  # │
    g[134] = box(0, 1, 0, 1)  # ┌
    g[135] = box(0, 1, 1, 0)  # ┐
    g[136] = box(1, 0, 0, 1)  # └
    g[137] = box(1, 0, 1, 0)  # ┘
    g[138] = box(1, 1, 0, 1)  # ├
    g[139] = box(1, 1, 1, 0)  # ┤
    g[140] = box(0, 1, 1, 1)  # ┬
    g[141] = box(1, 0, 1, 1)  # ┴
    g[142] = box(1, 1, 1, 1)  # ┼
    return g


def main():
    glyphs = parse(os.path.join(ROOT, "tools", "font.txt"))
    table = [[0] * H for _ in range(256)]
    for code, rows in glyphs.items():
        table[code] = to_bits(rows)
    for code, rows in generated().items():
        table[code] = rows
    # unknown printable -> boxed '?'
    out_path = os.path.join(ROOT, "src", "kernel", "gfx", "font_data.inc")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("// generated by tools/make_font.py from tools/font.txt - do not edit\n")
        for code in range(256):
            f.write("{" + ",".join("0x%02x" % v for v in table[code]) + "},\n")
    if "--preview" in sys.argv:
        from PIL import Image
        im = Image.new("L", (16 * 10, 16 * 14), 30)
        for code in range(256):
            gx, gy = (code % 16) * 10 + 1, (code // 16) * 14 + 1
            for y in range(H):
                for x in range(W):
                    if table[code][y] & (0x80 >> x):
                        im.putpixel((gx + x, gy + y), 255)
        im = im.resize((im.width * 3, im.height * 3), Image.NEAREST)
        im.save(sys.argv[sys.argv.index("--preview") + 1])


if __name__ == "__main__":
    main()
