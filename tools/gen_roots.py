"""Make src/kernel/net/roots.inc, silicon's TLS trust store, from the Mozilla root list that ships with
the Python `certifi` package.

    pip install certifi cryptography
    python tools/gen_roots.py [bundle.pem]

Each entry: u16 subject length, the subject Name exactly as DER, u8 key kind (1 RSA, 2 P-256, 3 P-384),
u16 length + (RSA modulus | EC point), u16 length + (RSA exponent | nothing).
Roots with other key types (P-521, Ed25519, ...) are left out.
"""
import re
import struct
import sys

from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa


def tlv(buf, pos):
    tag = buf[pos]
    l = buf[pos + 1]
    hdr = 2
    if l & 0x80:
        nb = l & 0x7F
        l = int.from_bytes(buf[pos + 2:pos + 2 + nb], "big")
        hdr = 2 + nb
    return tag, pos + hdr, l


def raw_subject(der):
    _, p, _ = tlv(der, 0)                 # Certificate
    _, p, _ = tlv(der, p)                 # TBSCertificate
    t, q, l = tlv(der, p)
    if t == 0xA0:                          # version
        p = q + l
    for _ in range(4):                     # serial, signature algorithm, issuer, validity
        _, q, l = tlv(der, p)
        p = q + l
    _, q, l = tlv(der, p)                  # subject
    return der[p:q + l]


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else __import__("certifi").where()
    pem = open(path, encoding="ascii").read()
    certs = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", pem, re.S)
    out = bytearray()
    kept = 0
    for c in certs:
        cert = x509.load_pem_x509_certificate(c.encode())
        der = cert.public_bytes(serialization.Encoding.DER)
        subj = raw_subject(der)
        key = cert.public_key()
        if isinstance(key, rsa.RSAPublicKey):
            nums = key.public_numbers()
            n = nums.n.to_bytes((nums.n.bit_length() + 7) // 8, "big")
            e = nums.e.to_bytes((nums.e.bit_length() + 7) // 8, "big")
            out += struct.pack(">H", len(subj)) + subj + bytes([1]) + struct.pack(">H", len(n)) + n + struct.pack(">H", len(e)) + e
        elif isinstance(key, ec.EllipticCurvePublicKey) and key.curve.name in ("secp256r1", "secp384r1"):
            pt = key.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
            out += struct.pack(">H", len(subj)) + subj + bytes([2 if key.curve.name == "secp256r1" else 3]) + struct.pack(">H", len(pt)) + pt + struct.pack(">H", 0)
        else:
            continue
        kept += 1
    with open("src/kernel/net/roots.inc", "w") as f:
        f.write("// generated by tools/gen_roots.py from the Mozilla root list (%d of %d roots); do not edit\n" % (kept, len(certs)))
        f.write("static const u8 ROOTS[] = {\n")
        for i in range(0, len(out), 24):
            f.write("    " + ",".join("0x%02x" % b for b in out[i:i + 24]) + ",\n")
        f.write("};\nstatic const u32 ROOTS_LEN = sizeof(ROOTS);\n")
    print("kept %d of %d roots, %d bytes" % (kept, len(certs), len(out)))


main()
