"""Turns the AAC Huffman codebooks of JAAD (public domain, https://github.com/dieterstueken/JAADec,
file aac/huffman/Codebooks.java) into src/kernel/media/aac_tables.inc.

    python tools/gen_aac_tables.py path/to/Codebooks.java
"""
import re
import sys

src = open(sys.argv[1]).read()
out = ["// generated by tools/gen_aac_tables.py from JAAD's Codebooks.java (public domain)",
       "// each row: bit length, code word, then 4 (books 1-4) or 2 (books 5-11) values; rows are sorted by (length, code)"]
names = ["HCB%d" % i for i in range(1, 12)] + ["HCB_SF"]
for name in names:
    m = re.search(r"int\[\]\[\] %s = \{(.*?)\n\t\};" % name, src, re.S)
    rows = re.findall(r"\{([^{}]*)\}", m.group(1))
    out.append("static const HuffRow %s[%d] = {" % (name.lower(), len(rows)))
    line = "   "
    for r in rows:
        v = [int(x) for x in r.split(",")]
        v += [0] * (6 - len(v))
        item = " {%d, %d, {%d, %d, %d, %d}}," % (v[0], v[1], v[2], v[3], v[4], v[5])
        if len(line) + len(item) > 118:
            out.append(line)
            line = "   "
        line += item
    out.append(line)
    out.append("};")
open("src/kernel/media/aac_tables.inc", "w").write("\n".join(out) + "\n")
print("ok")
